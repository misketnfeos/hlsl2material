def parse_t3d_clipboard(text: str) -> dict:
    """一步完成：解析 T3D 文本 → 返回前端可用的图数据 JSON"""
    parser = T3DParser()
    result = parser.parse(text)
    
    if result.errors:
        return {
            'error': '\n'.join(result.errors),
            'warnings': result.warnings,
        }
    
    graph_data = t3d_to_graph_data(result)
    graph_data['warnings'].extend(result.warnings)
    
    return {
        'graph': graph_data,
        'node_count': len(result.nodes),
    }


def parse_t3d_to_result(text: str) -> T3DParseResult:
    """解析 T3D 文本返回原始解析结果"""
    parser = T3DParser()
    return parser.parse(text)
