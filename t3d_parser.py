def _get_display_name(ue_class: str, node: T3DGraphNode) -> str:
    """获取友好显示名"""
    if ue_class in _DISPLAY_NAMES:
        name = _DISPLAY_NAMES[ue_class]
    else:
        # 从类名提取
        name = ue_class.replace('MaterialExpression', '').replace('MaterialGraphNode_', '')
        if not name:
            name = node.name

    # 对某些特殊节点增加额外信息
    if node.material_expression:
        props = node.material_expression.properties
        if ue_class == 'MaterialExpressionConstant' and 'R' in props:
            name = f'Const ({props["R"]})'
        elif ue_class == 'MaterialExpressionConstant3Vector' and 'Constant' in props:
            name = f'Color {props["Constant"][:30]}'
        elif ue_class == 'MaterialExpressionScalarParameter' and 'ParameterName' in props:
            pname = props['ParameterName'].strip('"')
            name = f'Param: {pname}'
        elif ue_class == 'MaterialExpressionVectorParameter' and 'ParameterName' in props:
            pname = props['ParameterName'].strip('"')
            name = f'Vec Param: {pname}'
        elif ue_class == 'MaterialExpressionCustom' and 'Description' in props:
            desc = props['Description'].strip('"')
            name = f'Custom: {desc[:20]}'
        elif ue_class == 'MaterialExpressionFunctionInput' and 'InputName' in props:
            iname = props['InputName'].strip('"')
            name = f'Input: {iname}'
        elif ue_class == 'MaterialExpressionTextureCoordinate' and 'CoordinateIndex' in props:
            ci = props['CoordinateIndex']
            name = f'TexCoord [{ci}]'

    return name


